"""Convert the legacy public pages into portable content for React Native views.

Run from mobile/: python scripts/extract_content.py
Requires beautifulsoup4 for this one-time authoring tool.
"""

import json
from pathlib import Path

from bs4 import BeautifulSoup, NavigableString, Tag

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parents[1] / "src" / "data"
PAGES = [
    "index", "index2", "index3", "404", "diretoria", "governanca",
    "infraestrutura", "etica", "transparencia", "comissao", "metodologia",
    "peneiras", "privacidade", "elenco", "loja",
]
SKIP = {"script", "style", "noscript", "svg", "iframe", "input", "select", "textarea"}
TEXT_TAGS = {"h1", "h2", "h3", "h4", "h5", "p", "li", "blockquote", "figcaption", "td", "th"}


def clean(value):
    return " ".join(value.split())


def extract(slug):
    soup = BeautifulSoup((ROOT / f"{slug}.html").read_text(encoding="utf-8"), "html.parser")
    title = clean(soup.title.get_text(" ", strip=True)) if soup.title else slug.title()
    if slug in {"elenco", "loja"}:
        roots = [soup.select_one("body > section"), soup.select_one("body > .container")]
    else:
        roots = [soup.select_one("main")]
    blocks = []

    def emit(block):
        if block.get("text") or block.get("src") or block.get("type") == "anchor":
            if block.get("type") == "text" and blocks and blocks[-1].get("type") == "text" and blocks[-1].get("text") == block.get("text"):
                return
            blocks.append(block)

    def walk(element):
        if not isinstance(element, Tag) or element.name in SKIP:
            return
        classes = element.get("class", [])
        if any(c in classes for c in ("sr-only", "material-symbols-outlined")):
            return
        if element.get("aria-hidden") == "true":
            return
        ident = element.get("id", "")
        if ident and element.name not in TEXT_TAGS and element.name not in {"a", "img"}:
            emit({"type": "anchor", "id": ident})
        if element.name == "img":
            src = element.get("src", "")
            if src.startswith("img/") and (ROOT / src).is_file():
                emit({"type": "image", "src": src, "alt": element.get("alt", "")})
            return
        if element.name == "a":
            href = element.get("href", "")
            label = clean(element.get_text(" ", strip=True))
            if href and label and href != "#":
                emit({"type": "link", "text": label, "href": href})
            return
        if element.name in TEXT_TAGS:
            value = clean(element.get_text(" ", strip=True))
            if value:
                emit({"type": "text", "tag": element.name, "text": value, **({"id": ident} if ident else {})})
            for link in element.find_all("a", href=True):
                href = link.get("href", "")
                if href and href != "#":
                    emit({"type": "link", "text": clean(link.get_text(" ", strip=True)) or href, "href": href})
            return
        if element.name == "button":
            label = clean(element.get_text(" ", strip=True))
            if label and element.get("onclick", "").startswith("filtrarCategoria"):
                emit({"type": "filter", "text": label})
            return
        if element.name == "span" and not element.find(True):
            value = clean(element.get_text(" ", strip=True))
            if len(value) > 5:
                emit({"type": "text", "tag": "span", "text": value})
            return
        for child in element.children:
            if isinstance(child, NavigableString):
                value = clean(str(child))
                if len(value) > 3:
                    emit({"type": "text", "tag": "p", "text": value})
            else:
                walk(child)

    for root in roots:
        if root:
            walk(root)
    return {"title": title, "blocks": blocks}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    pages = {name: extract(name) for name in PAGES}
    with (OUT / "pages.json").open("w", encoding="utf-8", newline="\n") as target:
        target.write(json.dumps(pages, ensure_ascii=False, indent=2) + "\n")
    image_root = OUT.parents[1] / "assets" / "images"
    lines = ["// Generated by scripts/extract_content.py", "import { ImageSourcePropType } from 'react-native';", "export const imageSources: Record<string, ImageSourcePropType> = {"]
    for path in sorted(image_root.rglob("*")):
        if path.is_file() and path.suffix.lower() in {".png", ".jpg", ".jpeg", ".webp"}:
            key = "img/" + path.relative_to(image_root).as_posix()
            rel = "../../assets/images/" + path.relative_to(image_root).as_posix()
            lines.append(f"  {json.dumps(key)}: require({json.dumps(rel)}),")
    lines.append("};")
    with (OUT / "imageSources.ts").open("w", encoding="utf-8", newline="\n") as target:
        target.write("\n".join(lines) + "\n")
    print({name: len(page["blocks"]) for name, page in pages.items()})


if __name__ == "__main__":
    main()
